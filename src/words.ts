export function getRandomWords(count: number): string[] {
  const shuffled = [...WORD_DICTIONARY].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function generateGameCards(): { word: string; type: 'normal' | 'secret' | 'black' }[] {
  const words = getRandomWords(25);
  const cards: { word: string; type: 'normal' | 'secret' | 'black' }[] = [];
  
  // 1 black word
  const blackIndex = Math.floor(Math.random() * 25);
  
  // 9 secret words (for the first player who joins)
  const secretIndices: number[] = [];
  while (secretIndices.length < 9) {
    const idx = Math.floor(Math.random() * 25);
    if (idx !== blackIndex && !secretIndices.includes(idx)) {
      secretIndices.push(idx);
    }
  }
  
  for (let i = 0; i < 25; i++) {
    if (i === blackIndex) {
      cards.push({ word: words[i], type: 'black' });
    } else if (secretIndices.includes(i)) {
      cards.push({ word: words[i], type: 'secret' });
    } else {
      cards.push({ word: words[i], type: 'normal' });
    }
  }
  
  return cards;
}
